LINK = re.compile(r'\[([^\]]*)\]\(([^)\s]*)\)')
SPLIT = re.compile(r'(\[[^\]]*\]\([^)\s]*\)|`[^`]*`)')
SECTION = re.compile(r'\b([Ss])ection (\d+)\b(?!\.\d)')
HEADING = re.compile(r'^(#{1,6}) (.*)$')


def slug(title):
    """GitHub's heading anchor."""
    text = title.strip().lower().replace('`', '')
    text = re.sub(r'[^\w\- ]', '', text)
    return text.replace(' ', '-')


def read(path):
    return (ROOT/path).read_text(encoding='utf-8')


def sections(text):
    """The guide as (level, title, body lines); the text before the first ## heading has level 1 and title ''."""
    out = [[1, '', []]]
    fence = False
    for line in text.split('\n'):
        if line.startswith('```'):
            fence = not fence
        match = None if fence else HEADING.match(line)
        if match and len(match.group(1)) == 1 and out[0][2] == [] and out[0][1] == '':
            continue
        if match and len(match.group(1)) in (2, 3):
            out.append([len(match.group(1)), match.group(2), []])
        else:
            out[-1][2].append(line)
    return [(level, title, body) for level, title, body in out]


def strip_title(text):
    """A file's own # title and the text after it."""
    lines = text.split('\n')
    if lines and lines[0].startswith('# '):
        return lines[0][2:].strip(), lines[1:]
    return None, lines


def property_since(number):
    """The API version that added a property id."""
    for since, ids in ((1, range(1, 6)), (2, range(6, 9)), (3, (9,)), (4, range(10, 16)), (5, (17,)),
                       (9, range(24, 28))):
        if number in ids:
            return since
    return 6


def hook_since(hook):
    """The API version that added a CMFCore hook."""
    return 9 if hook in cmf_pack.HOOKS9 else 6 if hook in cmf_pack.HOOKS6 else 4


def first_sentence(text):
    sentence = re.match(r'(.+?\.)(?= [A-Z`(]|$)', text)
    return (sentence.group(1) if sentence else text).replace('|', '\\|')


def clean(title):
    """A page title from a guide heading: no section number, no API version."""
    return short(re.sub(r'^\d+\. ', '', title))


def short(title):
    return re.sub(r' \(API versions? [^)]*\)$', '', title)


class Build:
    def __init__(self, wiki=False, repo_url='', branch='main'):
        self.wiki = wiki
        self.repo_url = repo_url.rstrip('/')
        self.branch = branch
        self.errors = []
        self.guide = sections(read(GUIDE))
        self.where = {}      # guide heading title -> (page, anchor or '')
        self.files = {}      # source file path -> page
        self.titles = {}     # page -> title
        self.derived = {}    # page -> the guide heading its title comes from
        self.file_heading = {}
        self.current = None

    def target(self, page, anchor=''):
        name = page if self.wiki else page + '.md'
        return name + ('#' + anchor if anchor else '')

    def plan(self):
        """Decides which page holds each guide heading, before any text is written."""
        used = set()
        for name, title, _group, sources in PAGES:
            guide_titles = [s['ref'] for s in sources if s['kind'] == 'guide']
            for source in sources:
                if source['kind'] == 'file':
                    self.files[source['ref']] = name
                    self.file_heading[source['ref']] = source['heading']
                    if title is None:
                        title = strip_title(read(source['ref']))[0]
            if title is None:
                title = clean(guide_titles[0])
                self.derived[name] = guide_titles[0]
            self.titles[name] = title
            for index, ref in enumerate(guide_titles):
                if ref in used:
                    self.errors.append('guide heading on two pages: %r' % ref)
                used.add(ref)
                first = index == 0 and (self.derived.get(name) == ref or ref == '')
                self.where[ref] = (name, '' if first else slug(self.heading_for(name, ref)))
        for level, title, _body in self.guide:
            if title not in used and title not in LEFT_OUT:
                self.errors.append('guide heading %r is on no page: add it to PAGES in tools/cmf_author_docs.py, '
                                   'or to LEFT_OUT' % title)
        for title in LEFT_OUT:
            if title not in [t for _l, t, _b in self.guide]:
                self.errors.append('LEFT_OUT names %r, which is not a guide heading' % title)

    def heading_for(self, page, ref):
        for name, _title, _group, sources in PAGES:
            if name == page:
                for source in sources:
                    if source['kind'] == 'guide' and source['ref'] == ref and source['heading']:
                        return source['heading']
        return ref

    # Text transforms, applied outside code blocks, links and inline code.

    def link(self, text, target, source):
        if re.match(r'^[a-z]+://', target) or target.startswith('#') or target.startswith('mailto:'):
            return '[%s](%s)' % (text, target)
        if target.startswith('page:'):
            page, _, anchor = target[5:].partition('#')
            if page not in self.titles:
                self.errors.append('%s: link to unknown page %r' % (source, page))
            return '[%s](%s)' % (text, self.target(page, anchor))
        path, _, anchor = target.partition('#')
        resolved = posixpath.normpath(posixpath.join(posixpath.dirname(source), path))
        if resolved == GUIDE:
            for ref, (page, page_anchor) in self.where.items():
                if anchor and slug(ref) == anchor:
                    return '[%s](%s)' % (text, self.target(page, page_anchor))
            if anchor:
                self.errors.append('%s: link to guide anchor #%s, which is no heading' % (source, anchor))
            return '[%s](%s)' % (text, self.target('Getting-Started'))
        if resolved in self.files:
            page = self.files[resolved]
            if page == self.current and not anchor and self.file_heading.get(resolved):
                return '[%s](#%s)' % (text, slug(self.file_heading[resolved]))
            return '[%s](%s)' % (text, self.target(page, anchor))
        if any(resolved.startswith(p) or p in resolved for p in PRIVATE):
            self.errors.append('%s: link to a private file: %s' % (source, resolved))
        if not (ROOT/resolved).exists():
            self.errors.append('%s: link to a missing file: %s' % (source, resolved))
        if self.wiki:
            kind = 'tree' if (ROOT/resolved).is_dir() else 'blob'
            url = '%s/%s/%s/%s' % (self.repo_url, kind, self.branch, resolved.rstrip('/'))
        else:
            url = posixpath.relpath(resolved, OUT) + ('/' if path.endswith('/') else '')
        return '[%s](%s)' % (text, url + ('#' + anchor if anchor else ''))

    def line(self, line, source, page):
        out = []
        for index, part in enumerate(SPLIT.split(line)):
            if index % 2 == 0:
                # Quoted titles become links first; a section reference inside a new link's text stays plain.
                pieces = SPLIT.split(self.prose_titles(part, page))
                out.append(''.join(self.sections_in(p, page) if i % 2 == 0 else p for i, p in enumerate(pieces)))
            elif part.startswith('['):
                match = LINK.match(part)
                out.append(self.link(match.group(1), match.group(2), source))
            else:
                out.append(part)
        return ''.join(out)

    def prose_titles(self, text, page):
        for ref, (target_page, anchor) in self.where.items():
            if not ref or re.match(r'^\d+\. ', ref) or (target_page == page and not anchor):
                continue
            name = short(ref)
            quoted = re.compile(r'"%s"(?: (?:below|above))?' % re.escape(name))
            text = quoted.sub(lambda m, n=name, t=target_page, a=anchor: '[%s](%s)' % (n, self.target(t, a)), text)
        return text

    def sections_in(self, text, page):
        def section(match):
            for ref, (target_page, anchor) in self.where.items():
                if ref.startswith(match.group(2) + '. '):
                    return '[%section %s](%s)' % (match.group(1), match.group(2), self.target(target_page, anchor))
            return match.group(0)
        return SECTION.sub(section, text)

    def body(self, lines, source, page, shift=0):
        out = []
        fence = False
        for line in lines:
            if line.startswith('```'):
                fence = not fence
                out.append(line)
                continue
            if fence:
                out.append(line)
                continue
            match = HEADING.match(line)
            if match and shift:
                line = '#' * min(6, len(match.group(1)) + shift) + ' ' + match.group(2)
            out.append(self.line(line, source, page))
        return out

    # Pages.

    def write_page(self, name, title, sources):
        self.current = name
        lines = [NOTE, '', '# ' + self.titles[name]]
        since = re.search(r'\((API versions? [^)]*)\)$', self.derived.get(name, ''))
        if since:
            lines += ['', '*Needs CMF %s or later.*' % since.group(1)]
        guide_levels = [lvl for lvl, t, _b in self.guide if t in [s['ref'] for s in sources if s['kind'] == 'guide']]
        lift = 1 if guide_levels and min(guide_levels) == 3 else 0
        for source in sources:
            if source['kind'] == 'guide':
                level, ref, body = next(s for s in self.guide if s[1] == source['ref'])
                if self.where[ref][1] or source['heading']:
                    lines += ['', '#' * (level - lift) + ' ' + (source['heading'] or ref)]
                lines += self.body(body, GUIDE, name)
            else:
                text = self.settings if source['ref'] == SETTINGS else read(source['ref'])
                if source['ref'] == THEME:
                    text = self.theme_text(text)
                _own, rest = strip_title(text)
                if source['heading']:
                    lines += ['', '## ' + source['heading']]
                lines += self.body(rest, source['ref'], name, source.get('shift', 0))
        return lines

    def finish(self, name, lines):
        order = [p[0] for p in PAGES]
        index = order.index(name)
        text = '\n'.join(lines)
        text = re.sub(r'\n{3,}', '\n\n', text).rstrip('\n')
        if CONTENTS in text:
            text = text.replace(CONTENTS, '\n'.join(self.contents()))
        nav = []
        if index > 0:
            nav.append('[Previous: %s](%s)' % (self.titles[order[index - 1]], self.target(order[index - 1])))
        if name != 'Home':
            nav.append('[Contents](%s)' % self.target('Home'))
        if index + 1 < len(order):
            nav.append('[Next: %s](%s)' % (self.titles[order[index + 1]], self.target(order[index + 1])))
        return text + '\n\n---\n\n' + ' · '.join(nav) + '\n'

    def contents(self):
        out = []
        group = None
        for name, _title, page_group, _sources in PAGES[1:]:
            if page_group != group:
                group = page_group
                out += ['', '**%s**' % group, '']
            out.append('- [%s](%s)' % (self.titles[name], self.target(name)))
        return out[1:]

    def sidebar(self):
        return '\n'.join(['[Home](Home)', ''] + self.contents()) + '\n'

    # Generated reference.

    def core(self):
        text = read(CORE)
        functions = {}
        for match in re.finditer(r'^function (CMF\w+)\(([^)]*)\)\s*(?::\s*([\w<>]+))?', text, re.M):
            params = re.sub(r'\s+', ' ', match.group(2)).strip()
            functions[match.group(1)] = '%s(%s)%s' % (match.group(1), params,
                                                       ' : ' + match.group(3) if match.group(3) else '')
        hooks = {}
        for match in re.finditer(r'^\s*public function (On\w+)\(([^)]*)\)\s*(?::\s*(\w+))?', text, re.M):
            params = re.sub(r'\s+', ' ', match.group(2)).strip()
            hooks[match.group(1)] = '%s(%s)%s' % (match.group(1), params,
                                                   ' : ' + match.group(3) if match.group(3) else '')
        hide = {}
        block = re.search(r'function CMFThemeHideWords\(part : name\) : string\s*\{(.*?)\n\}', text, re.S).group(1)
        parts = []
        for line in block.split('\n'):
            case = re.match(r"\s*case '(\w+)':", line)
            ret = re.match(r'\s*return "([^"]*)";', line)
            if case:
                parts.append(case.group(1))
            elif ret and parts:
                for part in parts:
                    hide[part] = ret.group(1)
                parts = []
        words = re.search(r'function CMFThemeTextKey\(key : name\) : bool\s*\{\s*return CMFListHas\((.*?), '
                          r'NameToString', text, re.S).group(1)
        text_keys = set(''.join(re.findall(r'"([^"]*)"', words)).split(','))
        listed = re.search(r'function CMFThemeParts\(\) : string\s*\{\s*return (.*?);', text, re.S).group(1)
        core_parts = ''.join(re.findall(r'"([^"]*)"', listed)).split(',')
        return functions, hooks, hide, text_keys, core_parts

    def version(self, call):
        if call in cmf_pack.PROPERTY_IDS:
            return property_since(cmf_pack.PROPERTY_IDS[call])
        for number in range(2, self.api() + 1):
            if call in getattr(cmf_pack, 'VERSION%d' % number, ()):
                return number
        return 1

    def api(self):
        """The API version cmfCore.ws reports (CMFGetVersion)."""
        return int(re.search(r'function CMFGetVersion\(\) : int \{ return (\d+); \}', read(CORE)).group(1))

    def mentions(self, word, texts):
        """Up to three pages that use a name: topic pages before adapter pages, those that use it most first."""
        pattern = re.compile(r'\b%s\b' % re.escape(word))
        counts = [(len(pattern.findall(text)), index, name) for index, (name, text) in enumerate(texts)
                  if name not in ('API-Reference', 'Abilities', 'Home')]
        found = [name for count, _index, name in sorted(counts, key=lambda c: (c[2].startswith('Adapter-'), -c[0], c[1])) if count][:3]
        return ', '.join('[%s](%s)' % (self.titles[n], self.target(n)) for n in found) or 'none'

    def describe(self, call, texts):
        """The first sentence of the call's row in a call table of the pages, or else of the first sentence of the
        pages' prose that uses the call."""
        row = re.compile(r'^\| [^|]*`%s\(.*?\| (.+?) \|$' % re.escape(call), re.M)
        for _name, text in texts:
            match = row.search(text)
            if match:
                return first_sentence(re.sub(r'^API version \d\. ', '', match.group(1)))
        for _name, text in texts:
            for line in text.split('\n'):
                if '`%s(' % call in line and not line.startswith(('|', '\t', '#', '- ')):
                    for sentence in re.split(r'(?<=\.) (?=[A-Z`])', line):
                        if '`%s(' % call in sentence:
                            return sentence.replace('|', '\\|')
        return ''

    def reference(self, texts):
        functions, hooks, _hide, _words, _parts = self.core()
        guide_text = read(GUIDE)
        lines = [NOTE, '', '# API reference', '',
                 'Every function, property id, hook and map event CMF offers to mods (API version %d). The '
                 'signatures are read from `cmfCore.ws`, and the list of calls from the pack tool, which refuses any '
                 'other `CMF...` call. "Since" is the API version that added it: check it with `CMFRequireVersion`, '
                 'or ask `CMFHasProperty` or `CMFHasAbility` first. "Explained on" names the pages that use it.'
                 % self.api(), '',
                 '## Functions', '', '| Function | Since | What it does | Explained on |', '| --- | --- | --- | --- |']
        calls = sorted(cmf_pack.API, key=lambda c: (self.version(c), c.startswith('CMFProperty'), c))
        for call in calls:
            if call not in functions:
                self.errors.append('the pack tool knows %s, but cmfCore.ws has no such function' % call)
                continue
            if not re.search(r'\b%s\b' % call, guide_text):
                self.errors.append('the guide never names %s: explain it in %s' % (call, GUIDE))
            what = self.describe(call, texts)
            if call in cmf_pack.PROPERTY_IDS:
                what = 'Returns property id `%d`.' % cmf_pack.PROPERTY_IDS[call]
            lines.append('| `%s` | %d | %s | %s |' % (functions[call], self.version(call), what,
                                                      self.mentions(call, texts)))
        lines += ['', '## Property ids', '',
                  'The generic calls `CMFRegister`, `CMFRegisterForTag` and `CMFStylePin` take one of these ids. '
                  'Write an id newer than the CMF you require as its number, behind `CMFHasProperty`. Ids 18 and 19 '
                  'are kept for later tooltip properties.', '',
                  '| Id | Function | Since | Explained on |', '| --- | --- | --- | --- |']
        ids = sorted(cmf_pack.PROPERTY_IDS.items(), key=lambda item: item[1])
        if set(cmf_pack.PROPERTY_IDS.values()) != cmf_pack.KNOWN_PROPERTIES:
            self.errors.append('PROPERTY_IDS and KNOWN_PROPERTIES differ in tools/cmf_pack.py')
        for call, number in ids:
            lines.append('| `%d` | `%s()` | %d | %s |' % (number, call, self.version(call), self.mentions(call, texts)))
        lines += ['', '## Hooks', '',
                  'Wrap these methods of `CMFCore` with `@wrapMethod(CMFCore)` and always call `wrappedMethod` so '
                  'other mods\' wrappers run too. A click hook acts only when `provider` is your own folder name and '
                  'passes every other call on.', '',
                  '| Hook | Since | Explained on |', '| --- | --- | --- |']
        for hook in cmf_pack.HOOKS:
            if hook not in hooks:
                self.errors.append('the pack tool knows the hook %s, but CMFCore has no such method' % hook)
                continue
            if not re.search(r'\b%s\b' % hook, guide_text):
                self.errors.append('the guide never names the hook %s' % hook)
            since = hook_since(hook)
            lines.append('| `%s` | %d | %s |' % (hooks[hook], since, self.mentions(hook, texts)))
        lines += ['', '## Map events', '',
                  'CMF\'s map calls these events on `CR4MapMenu` under CMF\'s own names. Add one with '
                  '`@addMethod(CR4MapMenu) event ...` to react.', '',
                  '| Event | Since | When | Explained on |', '| --- | --- | --- | --- |']
        for event, since, when in EVENTS:
            word = event.split('(')[0]
            if not re.search(r'\b%s\b' % word, guide_text):
                self.errors.append('the guide never names the event %s' % word)
            lines.append('| `%s` | %d | %s | %s |' % (event, since, when, self.mentions(word, texts)))
        lines += ['', '## What each API version added', '']
        for number in range(1, self.api() + 1):
            added = sorted(c for c in cmf_pack.API if self.version(c) == number)
            hooks_added = [h for h in cmf_pack.HOOKS if hook_since(h) == number]
            names = ['`%s`' % c for c in added] + ['hook `%s`' % h for h in hooks_added]
            lines.append('- **%d**: %s' % (number, ', '.join(names) or 'no new calls (new theme keys only)'))
        return lines

    def theme_tables(self):
        _functions, _hooks, hide, text_keys, core_parts = self.core()
        if core_parts != list(cmf_pack.THEME_PART_KEYS):
            self.errors.append('the parts in cmfCore.ws CMFThemeParts and tools/cmf_pack.py THEME_PART_KEYS differ')
        groups = [('glow keys', cmf_pack.THEME_GLOW), ('shadow keys', cmf_pack.THEME_SHADOW)]

        def keys(names, extra_groups=()):
            names = list(names)
            shown = []
            for label, group in list(extra_groups) + groups:
                if all(k in names for k in group):
                    names = [k for k in names if k not in group]
                    shown.append(label)
            shown += ['`%s`%s' % (k, ' (text)' if k in text_keys else '') for k in names]
            return ', '.join(shown) or 'none'
        text_group = [('text keys', ('font', 'size', 'color', 'spacing', 'align'))]
        def mark(names):
            return ', '.join('`%s`%s' % (k, ' (text)' if k in text_keys else '') for k in names)
        lines = ['### Key groups', '',
                 '- **text keys**: %s' % mark(('font', 'size', 'color', 'spacing', 'align')),
                 '- **glow keys**: %s' % ', '.join('`%s`' % k for k in cmf_pack.THEME_GLOW),
                 '- **shadow keys**: %s' % ', '.join('`%s`' % k for k in cmf_pack.THEME_SHADOW),
                 '- **box keys** (every kind but `line` and `movie`): %s' % mark(
                     k for k in cmf_pack.THEME_BOX if k not in cmf_pack.THEME_GLOW + cmf_pack.THEME_SHADOW)
                 + ', glow keys, shadow keys',
                 '- **map-space keys** (`line` and `movie`): %s' % mark(cmf_pack.THEME_SPACE),
                 '', '"(text)" marks a key whose value goes in the `text` argument.', '',
                 '### Parts and their style keys', '', '| Part | Style keys | `hide` words |', '| --- | --- | --- |']
        for part, names in cmf_pack.THEME_PART_KEYS.items():
            words = ', '.join('`%s`' % w for w in hide.get(part, '').split(',') if w) or 'none'
            lines.append('| `%s` | %s | %s |' % (part, keys(names, text_group), words))
        lines += ['', '### Drawing kinds and their keys', '',
                  '| Kind | Anchors | Keys | List keys |', '| --- | --- | --- | --- |']
        for kind, names in cmf_pack.THEME_KIND_KEYS.items():
            anchors = '`mapSpace` only' if kind in cmf_pack.THEME_SPACE_KINDS and kind != 'text' else (
                'any part, `mapSpace` or a drawing' if kind == 'text' else 'any part but `mapSpace`, or a drawing')
            names = list(names)
            shown = []
            for label, group in (('box keys', cmf_pack.THEME_BOX), ('map-space keys', cmf_pack.THEME_SPACE)):
                if all(k in names for k in group):
                    names = [k for k in names if k not in group]
                    shown.append(label)
            shown += ['`%s`%s' % (k, ' (text)' if k in text_keys else '') for k in names]
            lists = ', '.join('`%s`' % k for k in cmf_pack.THEME_LIST_KEYS.get(kind, ())) or (
                'any your movie documents' if kind == 'movie' else 'none')
            lines.append('| `%s` | %s | %s | %s |' % (kind, anchors, ', '.join(shown), lists))
        lines += ['', '### Layers', '', ', '.join('`%s`' % layer for layer in cmf_pack.THEME_LAYERS)]
        return lines

    def theme_text(self, text):
        begin, end = text.index(THEME_BEGIN), text.index(THEME_END)
        written = text[:begin]
        every = set(cmf_pack.THEME_PART_KEYS) | set(cmf_pack.THEME_KIND_KEYS) | set(cmf_pack.THEME_LAYERS)
        for names in list(cmf_pack.THEME_PART_KEYS.values()) + list(cmf_pack.THEME_KIND_KEYS.values()):
            every |= set(names)
        for names in cmf_pack.THEME_LIST_KEYS.values():
            every |= set(names)
        for key in sorted(every):
            if '`%s`' % key not in written:
                self.errors.append('%s: the theme key or name %s is not described above the tables' % (THEME, key))
        return text[:begin] + THEME_BEGIN + '\n' + '\n'.join(self.theme_tables()) + '\n' + text[end:]

    def settings_tables(self):
        """Every [CMFSettings] key with its in-game menu row, from cmfCore.ws CMFChoiceKeys, CMF's settings menu
        and the menu add-on's rows."""
        core = read(CORE)
        listed = re.search(r'function CMFChoiceKeys\(\) : string\s*\{\s*return (.*?);', core, re.S).group(1)
        keys = [k for k in ''.join(re.findall(r'"([^"]*)"', listed)).split(',') if k]
        stored = set(re.findall(r'<Var id="(\w+)"', read(SETTINGS_MENU)))
        strings = {e['key']: e['text']['en'] for e in json.loads(read(CHOICE_STRINGS))['strings']}
        rows = {}
        for group in re.finditer(r'<Group id="\w+" displayName="([^"]*)"(.*?)</Group>', read(CHOICE_MENU), re.S):
            path = [strings.get('panel_' + part, part) for part in group.group(1).split('.')[2:]]
            for var in re.finditer(r'<Var id="(\w+)"[^>]*? displayName="([^"]*)"', group.group(2)):
                rows[var.group(1)] = (' > '.join(path), var.group(2))
        lines = ['| File key | Feature | In-game menu page | Menu row |', '| --- | --- | --- | --- |']
        for key in keys:
            feature = key.split('_')[0]
            if 'CMFFile_' + key not in stored:
                self.errors.append('%s has no CMFFile_%s, which cmfCore.ws CMFChoiceKeys lists' % (SETTINGS_MENU, key))
            if 'CMFPick_' + key not in rows or 'CMFPick_' + feature not in rows:
                self.errors.append('%s has no row CMFPick_%s for the choice key %s' % (CHOICE_MENU, key, key))
                continue
            page, row = rows['CMFPick_' + key]
            lines.append('| `CMFFile_%s` | %s | %s | %s |' % (key, rows['CMFPick_' + feature][1], page, row))
        for key, var, feature in (('CMFFile_Fallthrough', 'CMFFallthrough', 'every feature'),
                                  ('CMFDebug', 'CMFReport', 'the log')):
            if key not in stored or var not in rows:
                self.errors.append('%s or %s lost %s' % (SETTINGS_MENU, CHOICE_MENU, key))
                continue
            lines.append('| `%s` | %s | %s | %s |' % (key, feature, rows[var][0], rows[var][1]))
        for number in range(1, 9):
            var = 'CMFOrder%d' % number
            if 'CMFProviderOrder%d' % number not in stored or var not in rows:
                self.errors.append('%s or %s lost CMFProviderOrder%d' % (SETTINGS_MENU, CHOICE_MENU, number))
                continue
            lines.append('| `CMFProviderOrder%d` | the Mod order | %s | %s |' % (number, rows[var][0], rows[var][1]))
        lines += ['', '`CMFFile_Fallthrough=Vanilla` makes a chosen mod that has nothing for a pin show the game\'s '
                  'own look there, instead of the next mod\'s. `CMFDebug=true` writes the who-wins report to the '
                  'script log. `CMFProviderOrder1` to `CMFProviderOrder8` hold one folder name each, earliest first.']
        return lines

    def settings_text(self, text):
        begin, end = text.index(SETTINGS_BEGIN), text.index(SETTINGS_END)
        return text[:begin] + SETTINGS_BEGIN + '\n' + '\n'.join(self.settings_tables()) + '\n' + text[end:]

    def run(self):
        self.settings = self.settings_text(read(SETTINGS))
        self.plan()
        out = {}
        for name, title, _group, sources in PAGES:
            if name != 'API-Reference':
                out[name] = self.write_page(name, title, sources)
        texts = [(name, '\n'.join(lines)) for name, lines in out.items()]
        out['API-Reference'] = self.reference(texts)
        pages = {}
        for name, _title, _group, _sources in PAGES:
            pages[name + '.md'] = self.finish(name, out[name])
        if self.wiki:
            pages['_Sidebar.md'] = self.sidebar()
        for name, text in pages.items():
            for word in PRIVATE:
                if word in text:
                    self.errors.append('%s names %r, which stays out of the public repository' % (name, word))
        theme = self.theme_text(read(THEME))
        return pages, theme


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('command', choices=('build', 'check'))
    parser.add_argument('--wiki', metavar='OUT', help='write GitHub Wiki pages to this folder instead')
    parser.add_argument('--repo-url', default='', help='the public repository, for --wiki links')
    parser.add_argument('--branch', default='main', help='the branch --wiki links point at (default main)')
    args = parser.parse_args()
    if args.wiki and not args.repo_url:
        parser.error('--wiki needs --repo-url')
    build = Build(wiki=bool(args.wiki), repo_url=args.repo_url, branch=args.branch)
    pages, theme = build.run()
    if build.errors:
        for error in dict.fromkeys(build.errors):
            print('error: ' + error)
        return 1
    folder = Path(args.wiki) if args.wiki else ROOT/OUT
    if args.command == 'check':
        stale = [name for name, text in pages.items()
                 if not (folder/name).exists() or (folder/name).read_text(encoding='utf-8') != text]
        extra = [p.name for p in folder.glob('*.md') if p.name not in pages] if folder.exists() else []
        if read(THEME) != theme:
            stale.append(THEME)
        if read(SETTINGS) != build.settings:
            stale.append(SETTINGS)
        for name in stale + extra:
            print('out of date: %s' % name)
        if stale or extra:
            print('run: python tools/cmf_author_docs.py build')
            return 1
        print('author pages are current (%d pages)' % len(pages))
        return 0
    folder.mkdir(parents=True, exist_ok=True)
    for old in folder.glob('*.md'):
        if old.name not in pages:
            old.unlink()
    for name, text in pages.items():
        (folder/name).write_bytes(text.encode('utf-8'))
    if not args.wiki:
        (ROOT/THEME).write_bytes(theme.encode('utf-8'))
        (ROOT/SETTINGS).write_bytes(build.settings.encode('utf-8'))
    print('wrote %d pages to %s' % (len(pages), folder))
    return 0


if __name__ == '__main__':
    sys.exit(main())
