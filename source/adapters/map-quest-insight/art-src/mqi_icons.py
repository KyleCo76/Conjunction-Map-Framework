"""Prepare Map Quest Insight's own icons for its CMF adapter and write the Sticker claim table.

Input: Wolfer's "MQI 2.0.1 icons for CMF.zip" extracted (SHA-256 2204facd...95d3; never committed). Output:
the adapter's art/ PNGs and content/scripts/local/zz_modcmfadaptermapquestinsight_sticker.ws. The pictures
are only cut and resized: CMF draws a pin picture across the longer side of the game's own icon, and
Wolfer's canvases carry room around each icon, so each cut keeps exactly the room CMF needs to draw the
icon at Map Quest Insight's own size.

  sticker_<name>.png   a square of the game icon's longer side (index.tsv vanilla_w/vanilla_h, map units)
                       around the Sticker's middle, so the Sticker comes out at its own drawn size
  badge_<name>.png     the round badge, the middle 31 of its 32 map units (ring and glow, with a clear edge)
  badgesym_<name>.png  the symbol scaled by its "symbol on badge" factor on the badge's canvas, cut the same
                       way, so it lies exactly over the badge (Wolfer's two-layer recipe)
  symbol_<name>.png    the symbol alone, the middle 18 of its 20 map units

Usage: python art-src/mqi_icons.py <extracted folder> [--check]
"""
import argparse
import csv
import hashlib
import io
from pathlib import Path
from PIL import Image

HERE = Path(__file__).resolve().parent
ADAPTER = HERE.parent / 'modCMFAdapterMapQuestInsight'
ART = ADAPTER / 'art'
TABLE = ADAPTER / 'content/scripts/local/zz_modcmfadaptermapquestinsight_sticker.ws'
ZIP_SHA256 = '2204facd0706bd05151a36e4039666e39792a94d1af213ad9ebc99678d8095d3'
SIZE = 64
BADGE_KEEP = 31.0   # of the badge canvas's 32 map units
SYMBOL_KEEP = 18.0  # of the symbol canvas's 20 map units
# README.txt, "BADGE AND SYMBOL NAMES": name, qmiIconKind, symbol on badge
KINDS = [('main', 1, 0.468), ('secondary', 2, 0.392), ('contract', 3, 0.454), ('treasure', 4, 0.430),
         ('gwent', 5, 0.430), ('horse_race', 6, 0.454), ('boat_race', 7, 0.478), ('fist_fight', 8, 0.459),
         ('heroes_pursuits', 9, 0.440), ('vintners_contract', 10, 0.401)]


def shrink(image):
    """Area-average down to SIZE with premultiplied alpha, as Wolfer's own sizes are made."""
    return image.convert('RGBa').resize((SIZE, SIZE), Image.LANCZOS).convert('RGBA')


def cut(image, cx, cy, side):
    side = int(round(side))
    left = int(round(cx - side / 2))
    top = int(round(cy - side / 2))
    canvas = Image.new('RGBA', (side, side), (0, 0, 0, 0))
    canvas.paste(image.crop((max(left, 0), max(top, 0), min(left + side, image.width), min(top + side, image.height))),
                 (max(-left, 0), max(-top, 0)))
    return canvas


def png(image):
    out = io.BytesIO()
    image.save(out, 'PNG', optimize=True)
    return out.getvalue()


def stickers(root):
    rows = []
    with open(root / 'Sticker/index.tsv', newline='', encoding='utf-8') as handle:
        for row in csv.DictReader(handle, delimiter='\t'):
            labels = [label.strip() for label in row['vanilla_labels'].split(',') if label.strip()]
            if labels:
                rows.append((row['name'], labels, float(row['vanilla_w']), float(row['vanilla_h'])))
    return rows


def build(root):
    files = {}
    for name, labels, width, height in stickers(root):
        image = Image.open(root / 'Sticker/256' / (name + '.png')).convert('RGBA')
        box = image.getchannel('A').getbbox()
        per_unit = image.width / 24.0
        files['sticker_%s.png' % name] = png(shrink(cut(image, (box[0] + box[2]) / 2.0, (box[1] + box[3]) / 2.0,
                                                         max(width, height) * per_unit)))
    for name, _, factor in KINDS:
        badge = Image.open(root / 'Badges/256' / (name + '.png')).convert('RGBA')
        symbol = Image.open(root / 'Symbols/256' / (name + '.png')).convert('RGBA')
        keep = badge.width * BADGE_KEEP / 32.0
        files['badge_%s.png' % name] = png(shrink(cut(badge, badge.width / 2.0, badge.height / 2.0, keep)))
        side = int(round(symbol.width * factor))
        layer = Image.new('RGBA', badge.size, (0, 0, 0, 0))
        small = symbol.convert('RGBa').resize((side, side), Image.LANCZOS).convert('RGBA')
        layer.alpha_composite(small, ((badge.width - side) // 2, (badge.height - side) // 2))
        files['badgesym_%s.png' % name] = png(shrink(cut(layer, badge.width / 2.0, badge.height / 2.0, keep)))
        files['symbol_%s.png' % name] = png(shrink(cut(symbol, symbol.width / 2.0, symbol.height / 2.0,
                                                       symbol.width * SYMBOL_KEEP / 20.0)))
    return files


def table(root):
    lines = []
    for name, labels, _, _ in stickers(root):
        for label in labels:
            lines.append('\tMqiAdapterSticker(on, \'%s\', "sticker_%s.png");' % (label, name))
    head = TABLE.read_text().split('\t// BEGIN generated by art-src/mqi_icons.py\n')[0]
    tail = TABLE.read_text().split('\t// END generated\n')[1]
    return head + '\t// BEGIN generated by art-src/mqi_icons.py\n' + '\n'.join(lines) + '\n\t// END generated\n' + tail


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('root', help="the extracted 'MQI 2.0.1 icons for CMF' folder")
    parser.add_argument('--check', action='store_true', help='compare instead of writing')
    args = parser.parse_args()
    root = Path(args.root)
    files = build(root)
    text = table(root)
    if args.check:
        bad = [n for n, data in files.items() if not (ART / n).exists() or (ART / n).read_bytes() != data]
        bad += [TABLE.name] if TABLE.read_text() != text else []
        print('\n'.join(bad) if bad else 'ok')
        raise SystemExit(1 if bad else 0)
    for name, data in files.items():
        (ART / name).write_bytes(data)
    TABLE.write_text(text)
    print('%d pictures, table %s' % (len(files), hashlib.sha256(text.encode()).hexdigest()[:8]))


if __name__ == '__main__':
    main()
